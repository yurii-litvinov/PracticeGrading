-- Персональный доступ участника к конкретной встрече.
CREATE TABLE "MeetingMemberAccesses" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "MeetingId" integer NOT NULL,
    "MemberId" integer NOT NULL,
    "TokenHash" character varying(64) NOT NULL,
    "Status" integer DEFAULT 0 NOT NULL,
    "CreatedAt" timestamp with time zone NOT NULL,
    "StatusChangedAt" timestamp with time zone,
    "StatusChangedByUserId" integer,

    CONSTRAINT "PK_MeetingMemberAccesses"
        PRIMARY KEY ("Id"),

    CONSTRAINT "CK_MeetingMemberAccesses_Status"
        CHECK ("Status" >= 0 AND "Status" <= 3),

    CONSTRAINT "FK_MeetingMemberAccesses_Meetings_MeetingId"
        FOREIGN KEY ("MeetingId")
        REFERENCES "Meetings" ("Id")
        ON DELETE CASCADE,

    CONSTRAINT "FK_MeetingMemberAccesses_Users_MemberId"
        FOREIGN KEY ("MemberId")
        REFERENCES "Users" ("Id")
        ON DELETE CASCADE,

    CONSTRAINT "FK_MeetingMemberAccesses_Users_StatusChangedByUserId"
        FOREIGN KEY ("StatusChangedByUserId")
        REFERENCES "Users" ("Id")
        ON DELETE SET NULL
);

CREATE UNIQUE INDEX "IX_MeetingMemberAccesses_TokenHash"
    ON "MeetingMemberAccesses" ("TokenHash");

CREATE INDEX "IX_MeetingMemberAccesses_MemberId"
    ON "MeetingMemberAccesses" ("MemberId");

CREATE INDEX "IX_MeetingMemberAccesses_MeetingId_Status"
    ON "MeetingMemberAccesses" ("MeetingId", "Status");

CREATE INDEX "IX_MeetingMemberAccesses_StatusChangedByUserId"
    ON "MeetingMemberAccesses" ("StatusChangedByUserId");

-- Постоянный доверенный доступ участника.
CREATE TABLE "TrustedMemberAccesses" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "MemberId" integer NOT NULL,
    "TokenHash" character varying(64) NOT NULL,
    "CreatedAt" timestamp with time zone NOT NULL,
    "RevokedAt" timestamp with time zone,

    CONSTRAINT "PK_TrustedMemberAccesses"
        PRIMARY KEY ("Id"),

    CONSTRAINT "FK_TrustedMemberAccesses_Users_MemberId"
        FOREIGN KEY ("MemberId")
        REFERENCES "Users" ("Id")
        ON DELETE CASCADE
);

CREATE UNIQUE INDEX "IX_TrustedMemberAccesses_MemberId"
    ON "TrustedMemberAccesses" ("MemberId");

CREATE UNIQUE INDEX "IX_TrustedMemberAccesses_TokenHash"
    ON "TrustedMemberAccesses" ("TokenHash");
