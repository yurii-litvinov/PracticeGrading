-- Новая связь многие-ко-многим между встречами и участниками.
CREATE TABLE "MeetingUser" (
    "MeetingsId" integer NOT NULL,
    "MembersId" integer NOT NULL,

    CONSTRAINT "PK_MeetingUser"
        PRIMARY KEY ("MeetingsId", "MembersId"),

    CONSTRAINT "FK_MeetingUser_Meetings_MeetingsId"
        FOREIGN KEY ("MeetingsId")
        REFERENCES "Meetings" ("Id")
        ON DELETE CASCADE,

    CONSTRAINT "FK_MeetingUser_Users_MembersId"
        FOREIGN KEY ("MembersId")
        REFERENCES "Users" ("Id")
        ON DELETE CASCADE
);

-- Сохраняем существующие связи до удаления Users.MeetingId.
INSERT INTO "MeetingUser" ("MeetingsId", "MembersId")
SELECT "MeetingId", "Id"
FROM "Users"
WHERE "MeetingId" IS NOT NULL;

-- Проверяем, что все старые связи перенесены.
DO $$
DECLARE
    old_relation_count integer;
    new_relation_count integer;
BEGIN
    SELECT count(*)
    INTO old_relation_count
    FROM "Users"
    WHERE "MeetingId" IS NOT NULL;

    SELECT count(*)
    INTO new_relation_count
    FROM "MeetingUser";

    IF old_relation_count <> new_relation_count THEN
        RAISE EXCEPTION
            'Meeting relations were not transferred: old=%, new=%',
            old_relation_count,
            new_relation_count;
    END IF;
END;
$$;

-- Старую связь удаляем только после успешного переноса.
ALTER TABLE "Users"
